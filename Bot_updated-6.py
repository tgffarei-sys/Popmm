def build_mute_list_keyboard(data: dict) -> InlineKeyboardMarkup:
    buttons = []
    for chat_id, users in data.get("group_mutes", {}).items():
        for uid, info in users.items():
            buttons.append([InlineKeyboardButton(
                f"🔊 {info.get('name', uid)}", callback_data=f"unmute|{chat_id}|{uid}",
            )])
    buttons.append([InlineKeyboardButton("↩️ بازگشت", callback_data="asettings")])
    return InlineKeyboardMarkup(buttons)


