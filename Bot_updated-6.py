def parse_channel_input(raw: str):
    """از روی یوزرنیم (@channel) یا لینک (t.me/channel) خام، دیکشنری {username, url} می‌سازه."""
    raw = raw.strip()
    if "t.me/" in raw:
        uname = raw.split("t.me/")[-1].split("?")[0].split("/")[0].lstrip("@")
    else:
        uname = raw.lstrip("@")
    uname = uname.strip()
    if not uname or not re.match(r"^[A-Za-z0-9_]{3,}$", uname):
        return None
    return {"username": f"@{uname}", "url": f"https://t.me/{uname}"}


