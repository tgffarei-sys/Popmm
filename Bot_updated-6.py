async def schedule_auto_delete(
    context: ContextTypes.DEFAULT_TYPE, chat_id: int, message_id: int, delay: int = None
) -> None:
    """
    پیام رو بعد از `delay` ثانیه حذف می‌کنه (اگه delay داده نشه، از تنظیمات فعلی خونده می‌شه).
    اگه job_queue در دسترس باشه ازش استفاده می‌کنه (سبک‌تره)، وگرنه با asyncio.sleep
    جایگزین می‌شه تا صرف‌نظر از نصب بودن یا نبودن بسته‌ی job-queue، همیشه کار کنه.
    """
    if delay is None:
        delay = get_cfg(load_data(), "auto_delete_seconds")
    if context.job_queue:
        context.job_queue.run_once(
            delete_message_later, delay, data={"chat_id": chat_id, "message_id": message_id}
        )
        return

    async def _delayed_delete() -> None:
        await asyncio.sleep(delay)
        try:
            await context.bot.delete_message(chat_id=chat_id, message_id=message_id)
        except TelegramError as e:
            logger.error("Failed to auto-delete message (fallback): %s", e)

    asyncio.create_task(_delayed_delete())


