def get_required_channels(data: dict = None) -> list:
    if data is None:
        data = load_data()
    return data.get("required_channels") or DEFAULT_CHANNELS


async def is_member(context: ContextTypes.DEFAULT_TYPE, user_id: int) -> bool:
    """کاربر باید توی همه‌ی کانال‌های required_channels عضو باشه، وگرنه False برمی‌گرده."""
    for ch in get_required_channels():
        try:
            member = await context.bot.get_chat_member(chat_id=ch["username"], user_id=user_id)
            if member.status not in ("member", "administrator", "creator"):
                return False
        except TelegramError as e:
            logger.error(
                "Membership check failed for channel %s / user %s: %s", ch["username"], user_id, e
            )
            return False
    return True


