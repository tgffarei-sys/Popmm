def _get_file_ids(entry: dict) -> list:
    """سازگاری با فایل‌های قدیمی (تکی: file_id) و قدیمی-چندتایی (file_ids، فقط یه نوع)."""
    if "file_ids" in entry:
        return entry["file_ids"]
    if "file_id" in entry:
        return [entry["file_id"]]
    return []


def _iter_file_send_items(entry: dict):
    """
    روی هر آیتم قابل‌ارسال یه entry از data['files'] پیمایش می‌کنه و (media_type, file_id) برمی‌گردونه.
    از هر سه فرمت پشتیبانی می‌کنه: تکی قدیمی، چندتایی قدیمی (یه نوع)، و mixed جدید (چند نوع مختلط).
    """
    if entry.get("type") == "mixed" and "items" in entry:
        for item in entry["items"]:
            yield item.get("type"), item.get("file_id")
    else:
        media_type = entry.get("type")
        for file_id in _get_file_ids(entry):
            yield media_type, file_id


