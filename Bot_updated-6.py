def _sum_sales_in_range(records: list, start_dt: datetime, end_dt: datetime = None) -> tuple:
    """روی لیستی از رسیدهای تاییدشده، تعداد و مجموع مبلغ توی بازه‌ی [start_dt, end_dt) رو حساب می‌کنه."""
    count, revenue = 0, 0
    for r in records:
        if r.get("status") != "approved":
            continue
        decided_str = r.get("decided_at")
        if not decided_str:
            continue
        try:
            decided = datetime.fromisoformat(decided_str)
        except ValueError:
            continue
        if decided < start_dt:
            continue
        if end_dt is not None and decided >= end_dt:
            continue
        count += 1
        revenue += r.get("price", 0)
    return count, revenue


def build_sales_stats_text(data: dict) -> str:
    """
    آمار فروش (خرید کوپن + اشتراک پریمیوم) به تفکیک امروز/دیروز/این هفته/این ماه.
    هفته از شنبه شروع می‌شه (مطابق هفته‌ی ایرانی).
    """
    now = datetime.utcnow()
    today_start = datetime(now.year, now.month, now.day)
    yesterday_start = today_start - timedelta(days=1)
    # پایتون: دوشنبه=0 ... شنبه=5، یکشنبه=6 — پس فاصله تا شنبه‌ی همین هفته:
    days_since_saturday = (today_start.weekday() - 5) % 7
    week_start = today_start - timedelta(days=days_since_saturday)
    month_start = datetime(now.year, now.month, 1)

    all_records = list(data.get("pending_receipts", {}).values()) + \
        list(data.get("pending_premium_receipts", {}).values())

    today_c, today_r = _sum_sales_in_range(all_records, today_start)
    yesterday_c, yesterday_r = _sum_sales_in_range(all_records, yesterday_start, today_start)
    week_c, week_r = _sum_sales_in_range(all_records, week_start)
    month_c, month_r = _sum_sales_in_range(all_records, month_start)

    return (
        "📊 *آمار فروش* (خرید کوپن + اشتراک پریمیوم)\n\n"
        f"📅 امروز: {today_c} فروش — {today_r:,} تومان\n"
        f"📅 دیروز: {yesterday_c} فروش — {yesterday_r:,} تومان\n"
        f"📅 این هفته (از شنبه): {week_c} فروش — {week_r:,} تومان\n"
        f"📅 این ماه: {month_c} فروش — {month_r:,} تومان"
    )


