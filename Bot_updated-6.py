def build_purchase_list_text(data: dict) -> str:
    receipts = data.get("pending_receipts", {})
    approved = [r for r in receipts.values() if r.get("status") == "approved"]
    if not approved:
        return "💳 *لیست خریدهای تاییدشده*\n\nهنوز خریدی تایید نشده."

    # جدیدترین‌ها اول
    approved.sort(key=lambda r: r.get("decided_at") or "", reverse=True)

    total_coupons = sum(r.get("coupons", 0) for r in approved)
    total_revenue = sum(r.get("price", 0) for r in approved)

