async def check_expired_premium_members(context: ContextTypes.DEFAULT_TYPE) -> None:
    """
    هر یه ساعت یه‌بار اجرا می‌شه (توی main() ثبت شده): اگه مدت اشتراک پریمیوم کسی تموم شده باشه،
    خودکار (چون ربات ادمین کاناله) اخراجش می‌کنه و بهش پیام می‌ده.
    """
    data = load_data()
    members = data.get("premium_members", {})
    if not members:
        return

    now = datetime.utcnow()
    expired_ids = []
    for uid_str, info in members.items():
        try:
            expires_at = datetime.fromisoformat(info["expires_at"])
        except (KeyError, ValueError):
            continue
        if expires_at > now:
            continue

        channel = info.get("channel")
        uid = int(uid_str)
        try:
            await context.bot.ban_chat_member(chat_id=channel, user_id=uid)
            await context.bot.unban_chat_member(chat_id=channel, user_id=uid, only_if_banned=True)
        except TelegramError as e:
            logger.error("Failed to kick expired premium member %s from %s: %s", uid, channel, e)

        try:
            await context.bot.send_message(
                chat_id=uid,
                text="⏳ مدت اشتراک پریمیوم شما تموم شد و از کانال خارج شدید. برای تمدید، از «💳 خرید کوپن → ⭐ اشتراک پریمیوم» اقدام کنید.",
            )
        except TelegramError:
            pass

        expired_ids.append(uid_str)

    if expired_ids:
        data = load_data()  # دوباره می‌خونیم که با تغییرات هم‌زمان دیگه تداخل نکنه
        for uid_str in expired_ids:
            data.get("premium_members", {}).pop(uid_str, None)
        save_data(data)


