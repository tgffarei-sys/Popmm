def chunk_buttons(flat_buttons: list, cols: int = 2) -> list:
    """یه لیست تخت از InlineKeyboardButton رو به ردیف‌های `cols`-تایی تقسیم می‌کنه."""
    return [flat_buttons[i:i + cols] for i in range(0, len(flat_buttons), cols)]


