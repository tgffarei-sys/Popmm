async def finish_multi_upload(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    user_id = update.effective_user.id
    session = PENDING_MULTI.pop(user_id, None)
    if not session:
        await update.message.reply_text("❌ هیچ آپلود فایل/مجموعه‌ای در حال انجام نیست.")
        return

    if not session["items"]:
        await update.message.reply_text("❌ چیزی نفرستادی، آپلود لغو شد.")
        return

    key = session["key"]
    data = load_data()

    if session["mode"] == "files":
        data["files"][key] = {"type": "mixed", "items": session["items"]}
        count = len(session["items"])
        save_data(data)
        await update.message.reply_text(
            f"✅ آپلود شد (کلید: «{key}») — {count} فایل توی بخش 🗂 فایل‌ها ذخیره شد."
        )
    elif session["mode"] == "games":
        default_price = get_cfg(data, "coupon_cost_game")
        data.setdefault("games", {})[key] = {"type": "mixed", "items": session["items"], "price": default_price}
        count = len(session["items"])
        save_data(data)
        await update.message.reply_text(
            f"✅ آپلود شد (کلید: «{key}») — {count} فایل توی بخش 🎮 بازی‌ها ذخیره شد "
            f"(قیمت: {default_price} کوپن، قابل تغییر از پنل)."
        )
    else:
        data["media_folders"][key] = {"items": session["items"]}
        count = len(session["items"])
        save_data(data)
        await update.message.reply_text(
            f"✅ آپلود شد (کلید: «{key}») — {count} مورد توی بخش 🎬📸 فیلم و عکس ذخیره شد."
        )


async def handle_file_upload(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    user_id = update.effective_user.id
    if not has_permission(load_data(), user_id, "upload_files"):
        return

    message = update.message

    # 🗂 اگه یه آپلود چندتایی (فایل‌ها یا مجموعه یا بازی) در حال انجامه، اولویت با اونه
    if user_id in PENDING_MULTI:
        session = PENDING_MULTI[user_id]
        if session["mode"] in ("files", "games"):
            if message.document:
                session["items"].append({"type": "document", "file_id": message.document.file_id})
            elif message.video:
                session["items"].append({"type": "video", "file_id": message.video.file_id})
            elif message.audio:
                session["items"].append({"type": "audio", "file_id": message.audio.file_id})
            else:
                await message.reply_text("⚠️ این نوع فایل توی این حالت آپلود قبول نمی‌شه.")
                return
            await message.reply_text(
                f"➕ اضافه شد ({len(session['items'])} فایل تا الان). ادامه بده یا «پایان آپلود» رو بزن."
            )
            return
        if session["mode"] == "media" and message.video:
            session["items"].append({"type": "video", "file_id": message.video.file_id})
            await message.reply_text(f"➕ ویدیو اضافه شد ({len(session['items'])} مورد تا الان). ادامه بده یا «پایان آپلود» رو بزن.")
            return
        await message.reply_text("⚠️ این نوع فایل توی این حالت آپلود قبول نمی‌شه.")
        return

    # آپلود تکی قدیمی (بدون تغییر)
    if user_id not in PENDING_FILE_UPLOADS:
        return

    if message.document:
        file_id, media_type = message.document.file_id, "document"
    elif message.video:
        file_id, media_type = message.video.file_id, "video"
    elif message.audio:
        file_id, media_type = message.audio.file_id, "audio"
    else:
        return  # نوع پشتیبانی‌نشده - چیزی مصرف نکن، شاید هندلر دیگه‌ای بخواد پردازشش کنه

    key = PENDING_FILE_UPLOADS.pop(user_id)
    data = load_data()
    data["files"][key] = {"file_id": file_id, "type": media_type}
    save_data(data)
    await message.reply_text(f"✅ آپلود شد (کلید: «{key}»)")


async def send_stored_file(update: Update, context: ContextTypes.DEFAULT_TYPE, key: str) -> None:
    data = load_data()
    file_entry = data.get("files", {}).get(key)
    if not file_entry:
        await update.message.reply_text("❌ فایلی با این نام ثبت نشده.")
        return

    delay = get_cfg(data, "auto_delete_seconds")
    caption = build_auto_delete_caption(delay)
    try:
        for media_type, file_id in _iter_file_send_items(file_entry):
            if media_type == "document":
                sent = await update.message.reply_document(file_id, caption=caption)
            elif media_type == "video":
                sent = await update.message.reply_video(file_id, caption=caption)
            elif media_type == "audio":
                sent = await update.message.reply_audio(file_id, caption=caption)
            else:
                continue
            await schedule_auto_delete(context, sent.chat_id, sent.message_id, delay)
    except TelegramError as e:
        logger.error("Failed to send stored file '%s': %s", key, e)
        await update.message.reply_text("❌ خطا در ارسال فایل. دوباره امتحان کن.")


async def send_media_folder(update: Update, context: ContextTypes.DEFAULT_TYPE, key: str) -> None:
    data = load_data()
    folder = data.get("media_folders", {}).get(key)
    if not folder or not folder.get("items"):
        await update.message.reply_text("❌ مجموعه‌ای با این نام ثبت نشده.")
        return

    delay = get_cfg(data, "auto_delete_seconds")
    caption = build_auto_delete_caption(delay)
    try:
        for item in folder["items"]:
            if item["type"] == "photo":
                sent = await update.message.reply_photo(item["file_id"], caption=caption)
            elif item["type"] == "video":
                sent = await update.message.reply_video(item["file_id"], caption=caption)
            else:
                continue
            await schedule_auto_delete(context, sent.chat_id, sent.message_id, delay)
    except TelegramError as e:
        logger.error("Failed to send media folder '%s': %s", key, e)
        await update.message.reply_text("❌ خطا در ارسال مجموعه. دوباره امتحان کن.")


