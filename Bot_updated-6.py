LINK_PATTERN = re.compile(
    r"(https?://\S+)"
    r"|(www\.\S+)"
    r"|(t\.me/\S+)"
    r"|(@[A-Za-z0-9_]{4,})"
    r"|([A-Za-z0-9-]+\.(com|ir|net|org|io|xyz|shop|site|online)\b)",
    re.IGNORECASE,
)


async def delete_links_and_ads(update: Update, context: ContextTypes.DEFAULT_TYPE) -> bool:
    """
    اگه پیام شامل لینک یا آیدی @ باشه، پاکش می‌کنه.
    پیام‌های ادمین‌ها هیچ‌وقت پاک نمی‌شن. بعد از ۳ اخطار، کاربر از گروه حذف می‌شه.
    """
    message = update.message
    if not message or not message.text:
        return False

    user_id = message.from_user.id
    if user_id in ADMIN_IDS:
        return False

    if not LINK_PATTERN.search(message.text):
        return False

    data = load_data()
    user_entry = get_user_entry(data, user_id)
    user_entry["warnings"] = user_entry.get("warnings", 0) + 1
    warnings = user_entry["warnings"]

    try:
        await message.delete()
    except TelegramError as e:
        logger.error("Failed to delete spam message: %s", e)

    if warnings >= 3:
        try:
            await context.bot.ban_chat_member(chat_id=message.chat_id, user_id=user_id)
            await context.bot.unban_chat_member(chat_id=message.chat_id, user_id=user_id)
            await context.bot.send_message(
                chat_id=message.chat_id,
                text=f"⛔️ {message.from_user.mention_html()} به دلیل ۳ بار ارسال لینک/تبلیغ از گروه اخراج شد.",
                parse_mode=ParseMode.HTML,
            )
        except TelegramError as e:
            logger.error("Failed to kick user %s: %s", user_id, e)
        user_entry["warnings"] = 0
    else:
        try:
            await context.bot.send_message(
                chat_id=message.chat_id,
                text=(
                    f"🚫 پیام {message.from_user.mention_html()} حذف شد (لینک/آیدی مجاز نیست).\n"
                    f"⚠️ اخطار {warnings} از ۳ — اخطار سوم یعنی حذف از گروه."
                ),
                parse_mode=ParseMode.HTML,
            )
        except TelegramError as e:
            logger.error("Failed to send warning message: %s", e)

    save_data(data)
    return True


# ============================================================
# 🔇 GROUP MODERATION: سکوت دستی + سکوت خودکار برای اسپم پشت‌سرهم
# ============================================================
SILENCE_CMD = re.compile(r"^سکوت\s*(\d+)\s*(دقیقه|ساعت)?$")
UNSILENCE_CMD = re.compile(r"^(لغو\s*سکوت|رفع\s*سکوت)$")

FLOOD_THRESHOLD = 5  # اگه یه نفر این تعداد پیام پشت‌سرهم بده (بدون اینکه کس دیگه‌ای وسطش پیام بده) → سکوت خودکار
FLOOD_TRACK: dict = {}  # chat_id -> {"user_id": int, "count": int}   (فقط توی حافظه، نیازی به ذخیره‌ی دائمی نیست)

FULL_UNMUTE_PERMISSIONS = ChatPermissions(
    can_send_messages=True,
    can_send_audios=True,
    can_send_documents=True,
    can_send_photos=True,
    can_send_videos=True,
    can_send_video_notes=True,
    can_send_voice_notes=True,
    can_send_polls=True,
    can_send_other_messages=True,
    can_add_web_page_previews=True,
)


async def mute_user(
    context: ContextTypes.DEFAULT_TYPE, chat_id: int, user_id: int, minutes: int, reason: str = ""
) -> bool:
    until_dt = datetime.utcnow() + timedelta(minutes=minutes)
    try:
        await context.bot.restrict_chat_member(
            chat_id=chat_id, user_id=user_id,
            permissions=ChatPermissions(can_send_messages=False), until_date=until_dt,
        )
    except TelegramError as e:
        logger.error("Failed to mute user %s in chat %s: %s", user_id, chat_id, e)
        return False

    try:
        member = await context.bot.get_chat_member(chat_id, user_id)
        name = member.user.full_name
    except TelegramError:
        name = f"کاربر {user_id}"

    data = load_data()
    chat_key = str(chat_id)
    data.setdefault("group_mutes", {}).setdefault(chat_key, {})
    data["group_mutes"][chat_key][str(user_id)] = {
        "until": until_dt.isoformat(), "name": name, "reason": reason,
    }
    save_data(data)

    try:
        text = f"🔇 {name} به مدت {minutes} دقیقه سکوت داده شد."
        if reason:
            text += f"\nدلیل: {reason}"
        await context.bot.send_message(chat_id=chat_id, text=text)
    except TelegramError:
        pass
    return True


async def unmute_user(context: ContextTypes.DEFAULT_TYPE, chat_id: int, user_id: int) -> bool:
    try:
        await context.bot.restrict_chat_member(
            chat_id=chat_id, user_id=user_id, permissions=FULL_UNMUTE_PERMISSIONS,
        )
    except TelegramError as e:
        logger.error("Failed to unmute user %s in chat %s: %s", user_id, chat_id, e)
        return False

    data = load_data()
    chat_key, uid_key = str(chat_id), str(user_id)
    chat_mutes = data.get("group_mutes", {}).get(chat_key)
    if chat_mutes and uid_key in chat_mutes:
        chat_mutes.pop(uid_key, None)
        if not chat_mutes:
            data["group_mutes"].pop(chat_key, None)
        save_data(data)

    try:
        await context.bot.send_message(chat_id=chat_id, text="🔊 سکوت این کاربر لغو شد.")
    except TelegramError:
        pass
    return True


async def handle_admin_group_commands(update: Update, context: ContextTypes.DEFAULT_TYPE) -> bool:
    """دستورهای ادمین که با ریپلای روی پیام یه نفر اجرا می‌شن: `سکوت 10` / `لغو سکوت`."""
    message = update.message
    text = (message.text or "").strip()
    if not message.reply_to_message or not message.reply_to_message.from_user:
        return False

    target_user = message.reply_to_message.from_user

    m = SILENCE_CMD.match(text)
    if m:
        amount = int(m.group(1))
        unit = m.group(2)
        minutes = amount * 60 if unit == "ساعت" else amount
        await mute_user(context, message.chat_id, target_user.id, minutes, reason="دستور دستی ادمین")
        try:
            await message.delete()
        except TelegramError:
            pass
        return True

    if UNSILENCE_CMD.match(text):
        await unmute_user(context, message.chat_id, target_user.id)
        try:
            await message.delete()
        except TelegramError:
            pass
        return True

    return False


async def check_flood(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    """
    اگه یه کاربر (غیرادمین) پشت‌سرهم (بدون اینکه کس دیگه‌ای وسطش پیام بده) پیام بده،
    بعد از FLOOD_THRESHOLD پیام، ۲ ساعت سکوت می‌شه.
    """
    message = update.message
    if not message or not message.from_user:
        return
    user_id = message.from_user.id
    chat_id = message.chat_id

    if user_id in ADMIN_IDS:
        FLOOD_TRACK.pop(chat_id, None)  # حرف زدن ادمین، استریک هرکسی رو می‌شکنه
        return

    track = FLOOD_TRACK.get(chat_id)
    if track and track["user_id"] == user_id:
        track["count"] += 1
    else:
        track = {"user_id": user_id, "count": 1}
        FLOOD_TRACK[chat_id] = track

    if track["count"] >= FLOOD_THRESHOLD:
        FLOOD_TRACK.pop(chat_id, None)
        await mute_user(
            context, chat_id, user_id, minutes=120,
            reason="ارسال پیام‌های پشت‌سرهم بدون اجازه دادن به بقیه",
        )


