def find_user_by_query(data: dict, query: str):
    """
    کاربر رو با آیدی عددی یا @یوزرنیم پیدا می‌کنه.
    خروجی: (target_id: int یا None, entry: dict یا None)
    """
    query = query.strip()

    if query.startswith("@"):
        username = query[1:].lower()
        for uid_str, entry in data.get("users", {}).items():
            stored_username = (entry.get("username") or "").lower()
            if stored_username == username:
                return int(uid_str), entry
        return None, None

    digits = fa_to_en_digits(query)
    if digits.isdigit():
        target_id = int(digits)
        entry = data.get("users", {}).get(str(target_id))
        return target_id, entry

    return None, None


