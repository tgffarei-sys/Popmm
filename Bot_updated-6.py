async def handle_photo(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    user_id = update.effective_user.id

    # 💳 اگه کاربر (ادمین یا غیرادمین) منتظر ارسال عکس رسید خریده، اول این رو چک کن
    if user_id in PENDING_RECEIPT:
        await handle_receipt_photo(update, context)
        return

    # ⭐ اگه کاربر منتظر ارسال عکس رسید خرید اشتراک پریمیومه
    if user_id in PENDING_PREMIUM_RECEIPT:
        await handle_premium_receipt_photo(update, context)
        return

    if not has_permission(load_data(), user_id, "upload_files"):
        return

    # 🎰 اگه ادمین در حالت آپلود بنر «بازی شانسی»ه، اولویت با اونه
    if await handle_banner_photo(update, context):
        return

    # 🗂 اگه یه آپلود «مجموعه» (عکس و فیلم) در حال انجامه، عکس رو به همون اضافه کن
    if user_id in PENDING_MULTI and PENDING_MULTI[user_id]["mode"] == "media":
        session = PENDING_MULTI[user_id]
        session["items"].append({"type": "photo", "file_id": update.message.photo[-1].file_id})
        await update.message.reply_text(
            f"➕ عکس اضافه شد ({len(session['items'])} مورد تا الان). ادامه بده یا «پایان آپلود» رو بزن."
        )
        return

    # آپلود تکی قدیمی (بدون تغییر)
    if user_id in PENDING_PHOTO_UPLOADS:
        key = PENDING_PHOTO_UPLOADS.pop(user_id)
        file_id = update.message.photo[-1].file_id
        data = load_data()
        data["photos"][key] = file_id
        save_data(data)
        await update.message.reply_text(f"✅ آپلود شد (کلید: «{key}»)")


