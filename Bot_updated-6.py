async def start(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    # /start فقط توی پیوی کار می‌کنه — داخل گروه/سوپرگروه نادیده گرفته می‌شه
    if update.effective_chat.type != "private":
        return

    user_id = update.effective_user.id

    await register_referral_if_needed(context, user_id, context.args)

    if not await is_member(context, user_id):
        await update.message.reply_text(
            LOCK_MESSAGE, parse_mode=ParseMode.MARKDOWN, reply_markup=join_keyboard()
        )
        return

    await update.message.reply_text(
        MAIN_MENU_TEXT, parse_mode=ParseMode.MARKDOWN, reply_markup=main_reply_keyboard(load_data(), user_id)
    )


