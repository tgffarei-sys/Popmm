            if entry:
                icon = _file_entry_icon(entry)
                send_items = list(_iter_file_send_items(entry))
                view_kb = build_file_view_keyboard(list_category, "file", key, is_admin_viewer)
                for i, (media_type, fid) in enumerate(send_items):
                    last = i == len(send_items) - 1
                    caption = f"{icon} کلید: `{key}` ({i + 1}/{len(send_items)})\nنوع: {media_type}"
                    if last:
                        caption += f"\n\n{build_auto_delete_caption(delay)}"
