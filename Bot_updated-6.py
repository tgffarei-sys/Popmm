async def register_referral_if_needed(context: ContextTypes.DEFAULT_TYPE, user_id: int, args) -> None:
    if not args:
        return
    payload = args[0]
    if not payload.startswith("ref_"):
        return

    try:
        referrer_id = int(payload.replace("ref_", "", 1))
    except ValueError:
        return

    if referrer_id == user_id:
        return  # جلوگیری از دعوت خود شخص

    # 🛡 فقط اگه کاربر جدید واقعاً عضو کانال شده باشه، حساب می‌شه —
    # جلوی فارم کردن با اکانت‌های ساختگی که هیچ‌وقت واقعاً عضو نمی‌شن رو می‌گیره.
    if not await is_member(context, user_id):
        return

    data = load_data()
    entry = get_user_entry(data, user_id)
    if entry.get("referred_by") is not None:
        return  # قبلاً یک‌بار زیرمجموعه‌ی کسی ثبت شده، دوباره حساب نمی‌شه

    entry["referred_by"] = referrer_id
    referrer_entry = get_user_entry(data, referrer_id)
    referrer_entry["referral_count"] = referrer_entry.get("referral_count", 0) + 1

    # 🛡 سقف روزانه: جلوی فارم کردن با تعداد زیاد اکانت در یه روز رو می‌گیره
    today_str = datetime.utcnow().date().isoformat()
    if referrer_entry.get("referrals_today_date") != today_str:
        referrer_entry["referrals_today_date"] = today_str
        referrer_entry["referrals_today"] = 0

    coupons_per_referral = get_cfg(data, "coupons_per_referral")
    max_referrals_per_day = get_cfg(data, "max_referrals_per_day")
    within_daily_limit = referrer_entry.get("referrals_today", 0) < max_referrals_per_day

    if within_daily_limit:
        referrer_entry["referrals_today"] = referrer_entry.get("referrals_today", 0) + 1
        referrer_entry["coupons"] = referrer_entry.get("coupons", 0) + coupons_per_referral
        data["stats"]["coupons_from_referrals"] = (
            data["stats"].get("coupons_from_referrals", 0) + coupons_per_referral
        )

    save_data(data)

    try:
        if within_daily_limit:
            await context.bot.send_message(
                chat_id=referrer_id,
                text=(
                    f"🎉 یک نفر با لینک دعوت شما وارد ربات شد!\n"
                    f"🎟 {coupons_per_referral} کوپن به موجودی شما اضافه شد."
                ),
            )
        else:
            await context.bot.send_message(
                chat_id=referrer_id,
                text=(
                    "👥 یک نفر دیگه با لینک شما وارد شد، ولی چون امروز به سقف "
                    f"{max_referrals_per_day} پاداش روزانه رسیدی، کوپنی اضافه نشد.\n"
                    "فردا دوباره فعال می‌شه."
                ),
            )
    except TelegramError as e:
        logger.error("Failed to notify referrer %s: %s", referrer_id, e)


