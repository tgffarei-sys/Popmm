def _db_connect():
    return psycopg2.connect(DATABASE_URL, sslmode="require")


def _db_ensure_table() -> None:
    conn = _db_connect()
    try:
        with conn.cursor() as cur:
            cur.execute(
                "CREATE TABLE IF NOT EXISTS bot_data (id INTEGER PRIMARY KEY, data JSONB NOT NULL)"
            )
        conn.commit()
    finally:
        conn.close()


